"""Compile a deployment spec into llama-server argv (and llama-swap YAML).

One function per command so the panel can preview exactly what will run — the preview route and the
engine call :func:`server_argv` with the same inputs.
"""

from __future__ import annotations

import shlex
from pathlib import Path
from typing import Any

from ..schemas import DeploymentSpec
from ..workbench.placement import ResolvedPlacement

# llama.cpp needs an upper bound; "auto" becomes this and the loader clamps it to the model depth.
ALL_LAYERS = 999


def _num(value: Any) -> str:
    return f"{float(value):.1f}"


def server_argv(*, bin_path: Path | str, model_path: Path | str, host: str, port: int | str, served_name: str,
                spec: DeploymentSpec, placed: ResolvedPlacement) -> list[str]:
    """argv for ``llama-server``. Ordering is stable so previews and logs diff cleanly."""
    args = [str(bin_path), "--model", str(model_path), "--host", host, "--port", str(port),
            "--alias", served_name, "--jinja", "--metrics"]
    if placed.gpus:
        args += ["--n-gpu-layers", str(placed.gpu_layers if placed.gpu_layers >= 0 else ALL_LAYERS)]
    else:
        args += ["--n-gpu-layers", "0"]
    if placed.split_mode != "none":
        args += ["--split-mode", placed.split_mode]
    if placed.tensor_split:
        args += ["--tensor-split", ",".join(_num(v) for v in placed.tensor_split)]
    if placed.main_gpu is not None and len(placed.gpus) > 1:
        args += ["--main-gpu", str(placed.main_gpu)]

    if placed.cpu_moe:
        args.append("--cpu-moe")
    elif placed.cpu_moe_layers is not None:
        args += ["--n-cpu-moe", str(placed.cpu_moe_layers)]
    for override in placed.tensor_overrides:
        args += ["--override-tensor", override]

    if placed.flash_attn != "auto":
        args += ["--flash-attn", placed.flash_attn]
    if placed.kv_k:
        args += ["--cache-type-k", placed.kv_k]
    if placed.kv_v:
        args += ["--cache-type-v", placed.kv_v]
    if not placed.kv_offload:
        args.append("--no-kv-offload")
    if not placed.mmap:
        args.append("--no-mmap")
    if placed.mlock:
        args.append("--mlock")
    args += ["--threads", str(placed.threads)]
    if placed.threads_batch:
        args += ["--threads-batch", str(placed.threads_batch)]
    if placed.parallel > 1:
        args += ["--parallel", str(placed.parallel)]

    ctx = spec.options.get("ctx")
    if ctx:
        args += ["--ctx-size", str(int(ctx))]
    template = spec.options.get("chat_template")
    if template:
        args += ["--chat-template", str(template)]
    extra = spec.options.get("extra_args")
    if isinstance(extra, list):
        args += [str(v) for v in extra]
    return args


def quantize_argv(*, bin_path: Path | str, source: Path | str, dest: Path | str, quant: str,
                  threads: int | None = None) -> list[str]:
    # b12189 ships llama-quantize with positional arguments: input, output, type.
    args = [str(bin_path), str(source), str(dest), quant.upper()]
    if threads:
        args += [str(threads)]
    return args


def split_argv(*, bin_path: Path | str, source: Path | str, out_dir: Path | str, max_size: str) -> list[str]:
    """``llama-gguf-split --split`` writes ``<name>-00001-of-0000N.gguf`` next to the source."""

    return [str(bin_path), "--split", "--split-max-size", max_size, "--out", str(out_dir), str(source)]


def format_cmd(cmd: list[str]) -> str:
    """Shell-ish rendering for logs. Never executed — the argv list is passed to exec directly."""
    return " ".join(shlex.quote(str(part)) for part in cmd)


def swap_model_entry(*, served_name: str, cmd: list[str], ttl: int, env: list[str] | None = None,
                     display_name: str | None = None) -> dict[str, Any]:
    """One ``models:`` entry for llama-swap.

    ``cmd`` stays a list here; :func:`swap_yaml` renders it as a block scalar because llama-swap takes
    one command string. ``${PORT}`` in the list is expanded by llama-swap at launch time.
    """
    entry: dict[str, Any] = {"cmd": [str(part) for part in cmd], "ttl": max(0, int(ttl))}
    if env:
        entry["env"] = [str(item) for item in env]
    if display_name:
        entry["name"] = display_name
    return entry


def swap_yaml(models: dict[str, dict[str, Any]], *, listen: str = "127.0.0.1:0", log_level: str = "info",
              health_timeout: int = 900) -> str:
    """Render a llama-swap config. Models are emitted in sorted order for reproducible files."""
    lines = ["# Generated by KaggleUI — rewritten whenever a llama-swap deployment changes.",
             "logLevel: " + log_level,
             f"healthCheckTimeout: {int(health_timeout)}",
             "models:"]
    if not models:
        lines.append("  {}")
    for name in sorted(models):
        entry = models[name]
        lines.append(f"  {_yaml_scalar(name)}:")
        if entry.get("name"):
            lines.append(f"    name: {_yaml_scalar(entry['name'])}")
        lines.append("    cmd: |")
        for part in entry["cmd"]:
            lines.append("      " + _cmd_token(part))
        lines.append(f"    ttl: {int(entry.get('ttl', 0))}")
        env = entry.get("env") or []
        if env:
            lines.append("    env:")
            for item in env:
                lines.append(f"      - {_yaml_scalar(item)}")
    return "\n".join(lines) + "\n"


def _cmd_token(part: str) -> str:
    """Quote one argv token for llama-swap's command parser; ``${PORT}`` must stay expandable."""
    if part == "${PORT}":
        return part
    if part and all(c.isalnum() or c in "._-/:@%+=" for c in part):
        return part
    return '"' + part.replace("\\", "\\\\").replace('"', '\\"') + '"'


def _yaml_scalar(text: str) -> str:
    """Quote a YAML scalar unless it is unambiguously safe."""
    safe = bool(text) and all(c.isalnum() or c in "._-/" for c in text)
    return text if safe else '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'
